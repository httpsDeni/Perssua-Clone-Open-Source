  function lang() {
    try {
      var s = window.Perssua && window.Perssua.state.settings.lang;
      return s || "pt";
    } catch (e) { return "pt"; }
  }

  function T(s) {
    if (s == null) return s;
    if (lang() === "en") return s;
    if (Object.prototype.hasOwnProperty.call(PT, s)) return PT[s];
    for (var i = 0; i < RULES.length; i++) {
      if (RULES[i][0].test(s)) return s.replace(RULES[i][0], RULES[i][1]);
    }
    return s;
  }

  function translateTree(root) {
    if (lang() === "en" || !root) return;
    var walker = document.createTreeWalker(root, window.NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentElement;
        if (!p) return window.NodeFilter.FILTER_REJECT;
        var tag = p.tagName;
        if (tag === "SCRIPT" || tag === "STYLE") return window.NodeFilter.FILTER_REJECT;
        return window.NodeFilter.FILTER_ACCEPT;
      },
    });
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (n) {
      var t = n.nodeValue;
      if (!t || !/[A-Za-z]{2}/.test(t)) return;
      var tr = T(t);
      if (tr !== t) { n.nodeValue = tr; return; }
      var trimmed = t.trim();
      if (trimmed !== t && T(trimmed) !== trimmed) {
        n.nodeValue = t.replace(trimmed, T(trimmed));
      }
    });
    var els = root.querySelectorAll ? root.querySelectorAll("[placeholder],[aria-label],[title]") : [];
    Array.prototype.forEach.call(els, function (e) {
      ["placeholder", "aria-label", "title"].forEach(function (a) {
        var v = e.getAttribute(a);
        if (v && /[A-Za-z]{2}/.test(v)) {
          var tr = T(v);
          if (tr !== v) e.setAttribute(a, tr);
        }
      });
    });
  }

  function applyStatic() {
    var l = lang();
    document.querySelectorAll("[data-i18n]").forEach(function (e) {
      e.textContent = l === "en" ? e.dataset.i18n : (PT[e.dataset.i18n] || e.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (e) {
      e.title = l === "en" ? e.dataset.i18nTitle : (PT[e.dataset.i18nTitle] || e.dataset.i18nTitle);
    });
    var tg = document.getElementById("lang-toggle");
    if (tg) tg.textContent = l === "pt" ? "PT · EN" : "EN · PT";
  }

  function setLang(l) {
    try {
      window.Perssua.state.settings.lang = l;
      window.Perssua.save();
    } catch (e) { /* pre-boot */ }
    applyStatic();
    if (window.Views) window.Views.go(document.body.dataset.view || "home");
    else translateTree(document.body);
    try { if (window.Notch) window.Notch.render(); } catch (e) { /* optional */ }
  }

  window.I18N = { T: T, setLang: setLang, translateTree: translateTree,
    applyStatic: applyStatic, lang: lang };
  window.T = T;
